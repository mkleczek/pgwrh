COMMENT ON TRIGGER version_lifecycle_check ON replication_group IS
    $comment$
Makes sure it is only possible to change current_version and target_version according to the following rules:
* If there is no configuration change in progress (ie. current_version = target_version) then it is only possible to change target_version
* If there is configuration change in progress it possible to either
** commit configuration change (ie. set current_version to target_version)
** or rollback configuration change (ie. set target_version to current_version)

It must not be possible to change current_version without changing target_version first.
$comment$;

