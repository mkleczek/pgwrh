It checks both local and remote shards to ensure consistency before allowing an update.
The check_replication_group_rollout_done trigger is designed to ensure that all hosts have confirmed their configuration changes for a given replication group version. When an update occurs, this trigger checks if the new current_version exists in both missing_connected_local_shard and missing_connected_remote_shard tables. If any of these tables lack entries for the new version, it raises an error indicating that not all hosts have completed the configuration rollout. This helps maintain data consistency by preventing updates until all nodes are up to date.

This trigger is crucial because it enforces a rollback mechanism in case there's an inconsistency after the update. By checking before applying any changes and ensuring all necessary configurations are in place, it helps maintain the integrity of the replication group across all participating hosts.
$comment$;

